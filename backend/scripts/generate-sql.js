/**
 * Generates database/siargao_pixel_life.sql (schema + seed data) from
 * backend/src/data/content.js. The resulting file can be opened and run in
 * MySQL Workbench (File > Open SQL Script > Execute) or with `npm run db:init`.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { touristSpots, npcs, quizzes, activities, missions, shopItems } from '../src/data/content.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '../../database/siargao_pixel_life.sql');

const esc = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'object') v = JSON.stringify(v);
  return `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
};
const spotId = (key) => `(SELECT id FROM tourist_spots WHERE spot_key = ${esc(key)})`;

const schema = `-- =====================================================================
--  SIARGAO PIXEL LIFE: ISLAND OF HOPE
--  "Play, Protect, and Rebuild Our Island."
--  MySQL 8 schema + seed data. Generated by backend/scripts/generate-sql.js
--  Import with MySQL Workbench (File > Open SQL Script > Execute All)
-- =====================================================================

CREATE DATABASE IF NOT EXISTS siargao_pixel_life
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE siargao_pixel_life;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS spot_visits, quiz_attempts, quiz_questions, quizzes, trash_pickups,
  activity_records, surfing_records, rewards, marine_conservation_records, cleanliness_records,
  mission_progress, missions, activities, npcs, shop_items, player_profiles, tourist_spots, users;
SET FOREIGN_KEY_CHECKS = 1;

-- ---------------------------------------------------------------------
-- Accounts
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username       VARCHAR(32)  NOT NULL,
  email          VARCHAR(255) NOT NULL,
  password_hash  VARCHAR(255) NOT NULL,
  role           ENUM('local_resident','tourist') NOT NULL,
  account_type   ENUM('player','admin') NOT NULL DEFAULT 'player',
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at  TIMESTAMP NULL DEFAULT NULL,
  UNIQUE KEY uq_users_username (username),
  UNIQUE KEY uq_users_email (email),
  KEY idx_users_role (role)
) ENGINE=InnoDB;

CREATE TABLE tourist_spots (
  id                      INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  spot_key                VARCHAR(40)  NOT NULL,
  name                    VARCHAR(120) NOT NULL,
  municipality            VARCHAR(120) NOT NULL DEFAULT '',
  description             TEXT NOT NULL,
  location_type           VARCHAR(40)  NOT NULL,
  cleanliness_percentage  DECIMAL(5,2) NOT NULL DEFAULT 70.00,
  environment_data        JSON NOT NULL,
  last_decay_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_active               TINYINT(1) NOT NULL DEFAULT 1,
  UNIQUE KEY uq_spots_key (spot_key),
  CONSTRAINT chk_spot_clean CHECK (cleanliness_percentage BETWEEN 0 AND 100)
) ENGINE=InnoDB;

CREATE TABLE player_profiles (
  id                INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id           INT UNSIGNED NOT NULL,
  level             INT UNSIGNED NOT NULL DEFAULT 1,
  experience        INT UNSIGNED NOT NULL DEFAULT 0,
  coins             INT UNSIGNED NOT NULL DEFAULT 300,
  surfing_skill     INT UNSIGNED NOT NULL DEFAULT 0,
  eco_points        INT UNSIGNED NOT NULL DEFAULT 0,
  appearance        JSON NULL,
  current_spot_id   INT UNSIGNED NULL,
  updated_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_profile_user (user_id),
  CONSTRAINT fk_profile_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_profile_spot FOREIGN KEY (current_spot_id) REFERENCES tourist_spots(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- World content
-- ---------------------------------------------------------------------
CREATE TABLE npcs (
  id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  npc_key          VARCHAR(40) NOT NULL,
  tourist_spot_id  INT UNSIGNED NOT NULL,
  name             VARCHAR(80) NOT NULL,
  npc_role         VARCHAR(80) NOT NULL,
  dialogue         JSON NOT NULL,
  info             TEXT NULL,
  UNIQUE KEY uq_npc_key (npc_key),
  KEY idx_npc_spot (tourist_spot_id),
  CONSTRAINT fk_npc_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE activities (
  id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  activity_key     VARCHAR(60) NOT NULL,
  tourist_spot_id  INT UNSIGNED NOT NULL,
  activity_name    VARCHAR(120) NOT NULL,
  activity_type    ENUM('cleanup','maintenance','surf','explore','kayak','community','quiz') NOT NULL,
  description      TEXT NOT NULL,
  config           JSON NULL,
  is_active        TINYINT(1) NOT NULL DEFAULT 1,
  UNIQUE KEY uq_activity_key (activity_key),
  KEY idx_activity_spot (tourist_spot_id),
  CONSTRAINT fk_activity_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE missions (
  id                 INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  mission_key        VARCHAR(60) NOT NULL,
  tourist_spot_id    INT UNSIGNED NOT NULL,
  title              VARCHAR(160) NOT NULL,
  description        TEXT NOT NULL,
  mission_category   ENUM('environmental_protection','beach_cleanup','marine_conservation','surfing',
                          'responsible_tourism','community_service','local_culture','exploration') NOT NULL,
  difficulty         ENUM('easy','medium','hard') NOT NULL DEFAULT 'easy',
  recommended_role   ENUM('local_resident','tourist','both') NOT NULL DEFAULT 'both',
  objectives         JSON NOT NULL,
  reward_xp          INT UNSIGNED NOT NULL DEFAULT 0,
  reward_coins       INT UNSIGNED NOT NULL DEFAULT 0,
  reward_badge       VARCHAR(120) NULL,
  is_repeatable      TINYINT(1) NOT NULL DEFAULT 0,
  cooldown_hours     INT UNSIGNED NOT NULL DEFAULT 6,
  is_active          TINYINT(1) NOT NULL DEFAULT 1,
  created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_mission_key (mission_key),
  KEY idx_mission_spot (tourist_spot_id),
  KEY idx_mission_category (mission_category),
  CONSTRAINT fk_mission_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE quizzes (
  id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  quiz_key         VARCHAR(60) NOT NULL,
  tourist_spot_id  INT UNSIGNED NOT NULL,
  title            VARCHAR(160) NOT NULL,
  category         ENUM('marine','tourism','environment','community') NOT NULL,
  pass_ratio       DECIMAL(3,2) NOT NULL DEFAULT 0.60,
  UNIQUE KEY uq_quiz_key (quiz_key),
  CONSTRAINT fk_quiz_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE quiz_questions (
  id             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  quiz_id        INT UNSIGNED NOT NULL,
  question       TEXT NOT NULL,
  options        JSON NOT NULL,
  correct_index  TINYINT UNSIGNED NOT NULL,
  explanation    TEXT NULL,
  sort_order     INT NOT NULL DEFAULT 0,
  KEY idx_question_quiz (quiz_id),
  CONSTRAINT fk_question_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE shop_items (
  id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  item_key         VARCHAR(60) NOT NULL,
  name             VARCHAR(120) NOT NULL,
  item_type        ENUM('surfboard','cosmetic','local_product') NOT NULL,
  price            INT UNSIGNED NOT NULL DEFAULT 0,
  tourist_spot_id  INT UNSIGNED NULL,
  description      TEXT NOT NULL,
  data             JSON NULL,
  UNIQUE KEY uq_item_key (item_key),
  CONSTRAINT fk_item_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Player progress & records
-- ---------------------------------------------------------------------
CREATE TABLE mission_progress (
  id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id       INT UNSIGNED NOT NULL,
  mission_id    INT UNSIGNED NOT NULL,
  progress      JSON NOT NULL,
  status        ENUM('active','completed','abandoned') NOT NULL DEFAULT 'active',
  started_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at  TIMESTAMP NULL DEFAULT NULL,
  KEY idx_mp_user_status (user_id, status),
  KEY idx_mp_mission (mission_id),
  CONSTRAINT fk_mp_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_mp_mission FOREIGN KEY (mission_id) REFERENCES missions(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE activity_records (
  id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id       INT UNSIGNED NOT NULL,
  activity_id   INT UNSIGNED NOT NULL,
  result        JSON NULL,
  completed_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_ar_user (user_id, completed_at),
  KEY idx_ar_activity (activity_id),
  CONSTRAINT fk_ar_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_ar_activity FOREIGN KEY (activity_id) REFERENCES activities(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE trash_pickups (
  id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id          INT UNSIGNED NOT NULL,
  tourist_spot_id  INT UNSIGNED NOT NULL,
  trash_index      SMALLINT UNSIGNED NOT NULL,
  picked_at        TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  KEY idx_tp_user_spot_time (user_id, tourist_spot_id, picked_at),
  CONSTRAINT fk_tp_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_tp_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE cleanliness_records (
  id                   INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id              INT UNSIGNED NOT NULL,
  tourist_spot_id      INT UNSIGNED NOT NULL,
  mission_id           INT UNSIGNED NULL,
  source               ENUM('pickup','mission','maintenance') NOT NULL DEFAULT 'pickup',
  cleanup_count        INT UNSIGNED NOT NULL DEFAULT 0,
  contribution_points  INT UNSIGNED NOT NULL DEFAULT 0,
  created_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_cr_spot (tourist_spot_id, created_at),
  KEY idx_cr_user (user_id),
  CONSTRAINT fk_cr_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_cr_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE CASCADE,
  CONSTRAINT fk_cr_mission FOREIGN KEY (mission_id) REFERENCES missions(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE marine_conservation_records (
  id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id          INT UNSIGNED NOT NULL,
  tourist_spot_id  INT UNSIGNED NOT NULL,
  activity_type    VARCHAR(60) NOT NULL,
  details          VARCHAR(255) NULL,
  completed_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_mcr_spot (tourist_spot_id),
  KEY idx_mcr_user (user_id),
  CONSTRAINT fk_mcr_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_mcr_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE rewards (
  id           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id      INT UNSIGNED NOT NULL,
  reward_key   VARCHAR(80) NOT NULL,
  reward_name  VARCHAR(160) NOT NULL,
  reward_type  ENUM('badge','achievement','certificate','surfboard','cosmetic','local_product') NOT NULL,
  earned_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_rewards_user (user_id, reward_type),
  CONSTRAINT fk_rewards_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE surfing_records (
  id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id          INT UNSIGNED NOT NULL,
  tourist_spot_id  INT UNSIGNED NOT NULL,
  challenge        ENUM('tutorial','beginner','intermediate','free') NOT NULL DEFAULT 'free',
  board_key        VARCHAR(60) NOT NULL,
  score            INT UNSIGNED NOT NULL,
  duration         DECIMAL(6,2) NOT NULL,
  waves            TINYINT UNSIGNED NOT NULL DEFAULT 1,
  carves           SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  passed           TINYINT(1) NOT NULL DEFAULT 0,
  completed_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_surf_score (tourist_spot_id, score),
  KEY idx_surf_user (user_id),
  CONSTRAINT fk_surf_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_surf_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE quiz_attempts (
  id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id     INT UNSIGNED NOT NULL,
  quiz_id     INT UNSIGNED NOT NULL,
  score       TINYINT UNSIGNED NOT NULL,
  total       TINYINT UNSIGNED NOT NULL,
  passed      TINYINT(1) NOT NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_qa_user (user_id),
  CONSTRAINT fk_qa_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_qa_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE spot_visits (
  id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id          INT UNSIGNED NOT NULL,
  tourist_spot_id  INT UNSIGNED NOT NULL,
  visited_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_visit_user (user_id, tourist_spot_id),
  CONSTRAINT fk_visit_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_visit_spot FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id) ON DELETE CASCADE
) ENGINE=InnoDB;
`;

const lines = [schema, '\n-- =====================================================================\n-- Seed data\n-- =====================================================================\n'];

for (const s of touristSpots) {
  lines.push(
    `INSERT INTO tourist_spots (spot_key, name, municipality, description, location_type, cleanliness_percentage, environment_data) VALUES (${[
      s.key, s.name, s.municipality, s.description, s.location_type, s.cleanliness, s.environment,
    ].map(esc).join(', ')});`
  );
}
lines.push('');
for (const n of npcs) {
  lines.push(
    `INSERT INTO npcs (npc_key, tourist_spot_id, name, npc_role, dialogue, info) VALUES (${esc(n.key)}, ${spotId(n.spot)}, ${[n.name, n.role, n.dialogue, n.info].map(esc).join(', ')});`
  );
}
lines.push('');
for (const a of activities) {
  lines.push(
    `INSERT INTO activities (activity_key, tourist_spot_id, activity_name, activity_type, description, config) VALUES (${esc(a.key)}, ${spotId(a.spot)}, ${[a.name, a.type, a.description, a.config].map(esc).join(', ')});`
  );
}
lines.push('');
for (const q of quizzes) {
  lines.push(
    `INSERT INTO quizzes (quiz_key, tourist_spot_id, title, category) VALUES (${esc(q.key)}, ${spotId(q.spot)}, ${esc(q.title)}, ${esc(q.category)});`
  );
  q.questions.forEach((qq, i) => {
    lines.push(
      `INSERT INTO quiz_questions (quiz_id, question, options, correct_index, explanation, sort_order) VALUES ((SELECT id FROM quizzes WHERE quiz_key = ${esc(q.key)}), ${[qq.q, qq.options, qq.answer, qq.explain, i].map(esc).join(', ')});`
    );
  });
}
lines.push('');
for (const m of missions) {
  lines.push(
    `INSERT INTO missions (mission_key, tourist_spot_id, title, description, mission_category, difficulty, recommended_role, objectives, reward_xp, reward_coins, reward_badge, is_repeatable) VALUES (${esc(m.key)}, ${spotId(m.spot)}, ${[
      m.title, m.description, m.category, m.difficulty, m.role, m.objectives, m.xp, m.coins, m.badge, m.repeatable,
    ].map(esc).join(', ')});`
  );
}
lines.push('');
for (const it of shopItems) {
  lines.push(
    `INSERT INTO shop_items (item_key, name, item_type, price, tourist_spot_id, description, data) VALUES (${[it.key, it.name, it.type, it.price].map(esc).join(', ')}, ${it.spot ? spotId(it.spot) : 'NULL'}, ${esc(it.description)}, ${esc(it.data)});`
  );
}
lines.push('\n-- Admin accounts are created with: cd backend && npm run create-admin -- <username> <email> <password>\n');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${OUT}`);
